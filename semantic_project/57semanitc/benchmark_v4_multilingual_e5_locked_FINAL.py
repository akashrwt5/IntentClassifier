#!/usr/bin/env python3
"""
V4 MULTILINGUAL E5-BASE — EXACT LOCKED 57-INTENT BENCHMARK

Uses the already-trained V4 E5 encoder + Logistic Regression classifier.

LOCKED TEST:
    /Users/shuklam/IntentClassifier/semantic_project/57semanitc/
    v3_57intent_locked_eval/locked_test_57intent.csv

This script:
- reads ONLY the canonical locked test CSV for evaluation
- does NOT retrain
- does NOT modify V3
- does NOT quantize
- does NOT export ONNX
- reports accuracy / macro F1 / weighted F1
- saves predictions, confusion matrix and summary
"""

from pathlib import Path
import json
import time
import re

import numpy as np
import pandas as pd
from sentence_transformers import SentenceTransformer
import joblib
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    classification_report,
    confusion_matrix,
)


PROJECT = Path(
    "/Users/shuklam/IntentClassifier/semantic_project/57semanitc"
)

V4_DIR = (
    PROJECT / "v4_multilingual_e5_base_semantic"
)

ENCODER_DIR = (
    V4_DIR / "e5_base_finetuned"
)

CLASSIFIER_PATH = (
    V4_DIR / "e5_base_logistic_classifier.joblib"
)

LABEL_MAP_PATH = (
    V4_DIR / "label_map.json"
)

LOCKED_CSV = (
    PROJECT
    / "v3_57intent_locked_eval"
    / "locked_test_57intent.csv"
)

OUT_DIR = (
    PROJECT
    / "v4_multilingual_e5_base_locked_benchmark"
)

OUT_DIR.mkdir(
    parents=True,
    exist_ok=True,
)

MAX_SEQ_LENGTH = 64
BATCH_SIZE = 64


def normalize_text(x):
    return (
        str(x)
        .strip()
        .replace("\n", " ")
        .replace("\r", " ")
    )


def add_e5_prefix(text):
    return "query: " + normalize_text(text)


def load_labels():
    obj = json.loads(
        LABEL_MAP_PATH.read_text(
            encoding="utf-8"
        )
    )

    # label_map generated by the V4 training script:
    # {"0": "IntentName", ...}
    if all(str(k).isdigit() for k in obj.keys()):
        return [
            obj[str(i)]
            for i in range(len(obj))
        ]

    # Defensive support for {"IntentName": index}
    return [
        k
        for k, _ in sorted(
            obj.items(),
            key=lambda kv: int(kv[1]),
        )
    ]


def find_columns(df):
    text_candidates = [
        "text",
        "utterance",
        "query",
        "sentence",
    ]

    label_candidates = [
        "intent",
        "label",
        "category",
    ]

    text_col = next(
        (
            c for c in text_candidates
            if c in df.columns
        ),
        None,
    )

    label_col = next(
        (
            c for c in label_candidates
            if c in df.columns
        ),
        None,
    )

    if text_col is None or label_col is None:
        raise RuntimeError(
            "Could not identify text/intent columns. "
            f"Columns found: {list(df.columns)}"
        )

    return text_col, label_col


def main():

    print("=" * 72)
    print(
        "V4 MULTILINGUAL E5-BASE — "
        "EXACT LOCKED 57-INTENT BENCHMARK"
    )
    print("=" * 72)

    required = [
        ENCODER_DIR,
        CLASSIFIER_PATH,
        LABEL_MAP_PATH,
        LOCKED_CSV,
    ]

    for path in required:
        if not path.exists():
            raise FileNotFoundError(
                f"Required path not found:\n{path}"
            )

    print()
    print(f"Encoder     : {ENCODER_DIR}")
    print(f"Classifier  : {CLASSIFIER_PATH}")
    print(f"Locked CSV  : {LOCKED_CSV}")

    # ---------------------------------------------------------------
    # LOAD LOCKED TEST
    # ---------------------------------------------------------------

    df = pd.read_csv(
        LOCKED_CSV
    )

    text_col, label_col = find_columns(
        df
    )

    df = df[
        [text_col, label_col]
    ].copy()

    df[text_col] = df[
        text_col
    ].map(normalize_text)

    df[label_col] = df[
        label_col
    ].map(normalize_text)

    df = df[
        (df[text_col] != "")
        & (df[label_col] != "")
    ].reset_index(drop=True)

    print()
    print(
        f"Rows        : {len(df)}"
    )
    print(
        f"Text column : {text_col}"
    )
    print(
        f"Label column: {label_col}"
    )
    print(
        f"Unique labels: {df[label_col].nunique()}"
    )

    if len(df) != 1686:
        raise RuntimeError(
            "LOCKED TEST ROW COUNT MISMATCH.\n"
            f"Expected exactly 1686 rows, found {len(df)}.\n"
            "Do not continue with a different test set."
        )

    if df[label_col].nunique() != 57:
        raise RuntimeError(
            "LOCKED TEST INTENT COUNT MISMATCH.\n"
            f"Expected 57 intents, found "
            f"{df[label_col].nunique()}."
        )

    labels = load_labels()

    if len(labels) != 57:
        raise RuntimeError(
            f"V4 label map contains {len(labels)} labels; "
            "expected 57."
        )

    # ---------------------------------------------------------------
    # LOAD MODEL
    # ---------------------------------------------------------------

    print()
    print(
        "Loading V4 fine-tuned E5 encoder..."
    )

    model = SentenceTransformer(
        str(ENCODER_DIR)
    )

    model.max_seq_length = (
        MAX_SEQ_LENGTH
    )

    classifier = joblib.load(
        CLASSIFIER_PATH
    )

    # ---------------------------------------------------------------
    # EMBEDDINGS
    # ---------------------------------------------------------------

    texts = [
        add_e5_prefix(x)
        for x in df[text_col].tolist()
    ]

    print()
    print(
        "Running E5 embedding inference..."
    )

    t0 = time.perf_counter()

    embeddings = model.encode(
        texts,
        batch_size=BATCH_SIZE,
        show_progress_bar=True,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )

    embedding_time = (
        time.perf_counter() - t0
    )

    # ---------------------------------------------------------------
    # CLASSIFIER
    # ---------------------------------------------------------------

    print()
    print(
        "Running classifier inference..."
    )

    t1 = time.perf_counter()

    pred_indices = classifier.predict(
        embeddings
    )

    classifier_time = (
        time.perf_counter() - t1
    )

    pred_labels = [
        labels[int(i)]
        for i in pred_indices
    ]

    true_labels = (
        df[label_col]
        .tolist()
    )

    # ---------------------------------------------------------------
    # METRICS
    # ---------------------------------------------------------------

    accuracy = accuracy_score(
        true_labels,
        pred_labels,
    )

    macro_f1 = f1_score(
        true_labels,
        pred_labels,
        labels=labels,
        average="macro",
        zero_division=0,
    )

    weighted_f1 = f1_score(
        true_labels,
        pred_labels,
        labels=labels,
        average="weighted",
        zero_division=0,
    )

    report = classification_report(
        true_labels,
        pred_labels,
        labels=labels,
        digits=4,
        zero_division=0,
    )

    cm = confusion_matrix(
        true_labels,
        pred_labels,
        labels=labels,
    )

    # ---------------------------------------------------------------
    # OUTPUTS
    # ---------------------------------------------------------------

    predictions = df.copy()

    predictions["prediction"] = (
        pred_labels
    )

    predictions["correct"] = (
        predictions[label_col]
        == predictions["prediction"]
    )

    predictions_path = (
        OUT_DIR
        / "locked_predictions_v4.csv"
    )

    predictions.to_csv(
        predictions_path,
        index=False,
    )

    report_path = (
        OUT_DIR
        / "locked_test_report_v4.txt"
    )

    report_text = (
        "# V4 MULTILINGUAL E5-BASE "
        "LOCKED 57-INTENT TEST\n\n"
        f"Rows       : {len(df)}\n"
        f"Accuracy   : {accuracy * 100:.4f}%\n"
        f"Macro F1   : {macro_f1 * 100:.4f}%\n"
        f"Weighted F1: {weighted_f1 * 100:.4f}%\n\n"
        "Classification report:\n"
        f"{report}\n"
    )

    report_path.write_text(
        report_text,
        encoding="utf-8",
    )

    cm_path = (
        OUT_DIR
        / "confusion_matrix_v4.csv"
    )

    pd.DataFrame(
        cm,
        index=labels,
        columns=labels,
    ).to_csv(
        cm_path
    )

    total_time = (
        embedding_time
        + classifier_time
    )

    rows_per_sec = (
        len(df) / total_time
        if total_time > 0
        else 0.0
    )

    ms_per_row = (
        total_time * 1000 / len(df)
        if len(df) > 0
        else 0.0
    )

    summary = {
        "model": "multilingual-e5-base",
        "encoder": str(ENCODER_DIR),
        "classifier": str(CLASSIFIER_PATH),
        "locked_csv": str(LOCKED_CSV),
        "rows": int(len(df)),
        "num_intents": int(df[label_col].nunique()),
        "accuracy": float(accuracy),
        "macro_f1": float(macro_f1),
        "weighted_f1": float(weighted_f1),
        "embedding_time_sec": float(embedding_time),
        "classifier_time_sec": float(classifier_time),
        "total_inference_time_sec": float(total_time),
        "rows_per_sec": float(rows_per_sec),
        "ms_per_row": float(ms_per_row),
        "quantization": False,
        "onnx": False,
        "training_performed": False,
        "locked_test_used": True,
    }

    summary_path = (
        OUT_DIR
        / "benchmark_summary_v4.json"
    )

    summary_path.write_text(
        json.dumps(
            summary,
            indent=2,
        ),
        encoding="utf-8",
    )

    # ---------------------------------------------------------------
    # PRINT
    # ---------------------------------------------------------------

    print()
    print("=" * 72)
    print(
        "--- V4 MULTILINGUAL E5-BASE "
        "LOCKED TEST RESULT ---"
    )
    print("=" * 72)

    print(
        f"Accuracy   : {accuracy * 100:.4f}%"
    )
    print(
        f"Macro F1   : {macro_f1 * 100:.4f}%"
    )
    print(
        f"Weighted F1: {weighted_f1 * 100:.4f}%"
    )

    print()
    print(report)

    print(
        "--- INFERENCE SPEED ---"
    )
    print(
        f"Total rows : {len(df)}"
    )
    print(
        f"Embedding time : "
        f"{embedding_time:.4f} sec"
    )
    print(
        f"Classifier time: "
        f"{classifier_time:.4f} sec"
    )
    print(
        f"Total time : "
        f"{total_time:.4f} sec"
    )
    print(
        f"Rows/sec   : "
        f"{rows_per_sec:.2f}"
    )
    print(
        f"ms/row     : "
        f"{ms_per_row:.4f}"
    )

    print()
    print("Saved:")
    print(predictions_path)
    print(report_path)
    print(cm_path)
    print(summary_path)

    print()
    print(
        "STATUS: V4 MULTILINGUAL E5-BASE "
        "LOCKED 57-INTENT BENCHMARK COMPLETE"
    )


if __name__ == "__main__":
    main()
